-- Импорт выписки не заполнял amount_base (оставался 0 по умолчанию), из-за чего
-- статистика, бюджеты и AI считали импортированные траты нулевыми.
-- Для операций в базовой валюте пользователя сумма в базе равна сумме (курс 1).
-- Операции в другой валюте пересчитываются по сохранённому курсу, если он задан;
-- курс 1 по умолчанию для них не трогаем — его нельзя восстановить задним числом.
UPDATE "transactions" t
SET "amount_base" = t."amount", "rate" = 1
FROM "users" u
WHERE u."id" = t."user_id"
  AND t."import_hash" IS NOT NULL
  AND t."amount_base" = 0
  AND t."amount" <> 0
  AND t."currency" = u."currency";
